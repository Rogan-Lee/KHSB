#!/usr/bin/env node
// SEED Design(@seed-design/css) 의 라이트 테마 토큰을 React Native 용 TS 상수로 변환한다.
// 웹 학생 포털(/s/[token])과 같은 값(색·타이포·간격·라운드)을 앱에서 그대로 쓰기 위함.
//
//   cd apps/mobile && npm run gen:seed
//
// 입력: apps/mobile/node_modules/@seed-design/css/base.css (devDependency — 웹 루트와 같은 버전으로 맞출 것)
// 출력: apps/mobile/src/design/seed-tokens.ts (직접 수정 금지 — 다시 생성할 것)

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(here, '..');
const repoRoot = path.resolve(appRoot, '../..');
const seedDir = path.join(appRoot, 'node_modules/@seed-design/css');
const cssPath = path.join(seedDir, 'base.css');
const pkg = JSON.parse(fs.readFileSync(path.join(seedDir, 'package.json'), 'utf8'));
const outPath = path.resolve(here, '../src/design/seed-tokens.ts');

const css = fs.readFileSync(cssPath, 'utf8');

// ── 1) 최상위 블록 중 ":root {" 와 라이트 테마 블록만 수집 (다크·미디어쿼리 블록 제외)
const vars = new Map();
const blockRe = /(^|\n)([^{}\n][^{}]*?)\{([^{}]*)\}/g;
for (const m of css.matchAll(blockRe)) {
  const selector = m[2].trim();
  const isRoot = selector === ':root';
  const isLight = selector.startsWith(':root,') && selector.includes('light-only') && !selector.includes('dark');
  if (!isRoot && !isLight) continue;
  for (const d of m[3].matchAll(/--seed-([a-z0-9_-]+)\s*:\s*([^;]+);/g)) {
    vars.set(d[1], d[2].trim());
  }
}

function resolve(value, depth = 0) {
  if (depth > 20) throw new Error(`var() 순환: ${value}`);
  return value.replace(/var\(--seed-([a-z0-9_-]+)(?:\s*,\s*([^)]+))?\)/g, (_, name, fallback) => {
    const v = vars.get(name);
    if (v == null) {
      if (fallback != null) return resolve(fallback.trim(), depth + 1);
      throw new Error(`정의 없는 토큰: --seed-${name}`);
    }
    return resolve(v, depth + 1);
  });
}

const camel = (s) => s.replace(/[-_]([a-z0-9])/g, (_, c) => c.toUpperCase());
const px = (v) => {
  const m = v.match(/(-?[\d.]+)px/);
  if (!m) throw new Error(`px 값 아님: ${v}`);
  return Number(m[1]);
};

// ── 2) 분류
const color = { palette: {}, bg: {}, fg: {}, stroke: {} };
const dimension = {};
const radius = {};
const fontSize = {};
const lineHeight = {};
const fontWeight = {};
const duration = {};
const shadow = {};

for (const [name, raw] of vars) {
  let m;
  if ((m = name.match(/^color-(palette|bg|fg|stroke)-(.+)$/))) {
    color[m[1]][camel(m[2])] = resolve(raw).toLowerCase();
  } else if ((m = name.match(/^dimension-(x[\d_]+)$/))) {
    dimension[m[1]] = px(resolve(raw));
  } else if ((m = name.match(/^radius-(r[\d_]+|full)$/))) {
    radius[m[1]] = px(resolve(raw));
  } else if ((m = name.match(/^font-size-(t\d+)-static$/))) {
    fontSize[m[1]] = px(resolve(raw));
  } else if ((m = name.match(/^line-height-(t\d+)-static$/))) {
    lineHeight[m[1]] = px(resolve(raw));
  } else if ((m = name.match(/^font-weight-(regular|medium|bold)$/))) {
    fontWeight[m[1]] = resolve(raw);
  } else if ((m = name.match(/^duration-(d\d)$/))) {
    const v = resolve(raw);
    duration[m[1]] = v.endsWith('ms') ? Number(v.slice(0, -2)) : Math.round(Number(v.slice(0, -1)) * 1000);
  } else if ((m = name.match(/^shadow-(s\d)$/))) {
    // "0px 2px 10px 0px #0000001a" → RN shadow 파라미터
    const v = resolve(raw).split(/\s+/);
    const hex = v[4];
    const alpha = hex.length === 9 ? parseInt(hex.slice(7, 9), 16) / 255 : 1;
    shadow[m[1]] = {
      offsetX: parseFloat(v[0]),
      offsetY: parseFloat(v[1]),
      radius: parseFloat(v[2]),
      opacity: Math.round(alpha * 1000) / 1000,
    };
  }
}

const sortKeys = (o) =>
  Object.fromEntries(
    Object.entries(o).sort(([a], [b]) => a.localeCompare(b, 'en', { numeric: true }))
  );

for (const k of Object.keys(color)) color[k] = sortKeys(color[k]);

const out = `// AUTO-GENERATED by apps/mobile/scripts/gen-seed-tokens.mjs — 직접 수정 금지.
// 원본: @seed-design/css@${pkg.version} base.css (라이트 테마). 웹 학생 포털과 같은 값.

export const seedColor = ${JSON.stringify(color, null, 2)} as const;

/** 간격·크기 (px) — 웹의 p-x4, gap-x3 … */
export const seedDimension = ${JSON.stringify(sortKeys(dimension), null, 2)} as const;

/** 라운드 (px) — 웹의 rounded-r4 … */
export const seedRadius = ${JSON.stringify(sortKeys(radius), null, 2)} as const;

/** 글자 크기 (px, static) — t1 … t14 */
export const seedFontSize = ${JSON.stringify(sortKeys(fontSize), null, 2)} as const;

/** 줄 높이 (px, static) — t1 … t14 */
export const seedLineHeight = ${JSON.stringify(sortKeys(lineHeight), null, 2)} as const;

export const seedFontWeight = ${JSON.stringify(fontWeight, null, 2)} as const;

/** 모션 길이 (ms) */
export const seedDuration = ${JSON.stringify(sortKeys(duration), null, 2)} as const;

/** 그림자 s1 … s3 */
export const seedShadow = ${JSON.stringify(sortKeys(shadow), null, 2)} as const;
`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, out);
console.log(
  `✓ ${path.relative(repoRoot, outPath)} — palette ${Object.keys(color.palette).length}, bg ${Object.keys(color.bg).length}, fg ${Object.keys(color.fg).length}, stroke ${Object.keys(color.stroke).length}, text ${Object.keys(fontSize).length}`
);
